# Программа читает числа до нуля и выводит сумму и количество чисел. В программе три ошибки.
# Исправьте их.
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     5
#     7
#     0
#   в терминале:
#     Число (0 — конец): 5
#     Число (0 — конец): 7
#     Число (0 — конец): 0
#     Сумма: 12
#     Количество: 2
# Пример 2
#   ввод:
#     0
#   в терминале:
#     Число (0 — конец): 0
#     Сумма: 0
#     Количество: 0
# Пример 3
#   ввод:
#     10
#     -3
#     8
#     0
#   в терминале:
#     Число (0 — конец): 10
#     Число (0 — конец): -3
#     Число (0 — конец): 8
#     Число (0 — конец): 0
#     Сумма: 15
#     Количество: 3

# Решение: исправьте программу ниже
total = 0
count = 0

while True:
    grade = int(input('Оценка (0 — конец): '))
    if grade == 0:
        break
    total += grade
    count += 1

if count == 0:
    print('Оценок нет')
else:
    print(f'Средний балл: {total / count:.2f}')