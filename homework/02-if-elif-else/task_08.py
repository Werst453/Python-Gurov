# Сервис каршеринга удерживает с клиента штраф за превышение скорости. Превышение — разница между
# фактической и разрешённой скоростью. При превышении до 20 км/ч включительно штрафа нет, от 21 до
# 40 — 750 руб., от 41 до 60 — 1500 руб., от 61 до 80 — 2500 руб., больше 80 — 5000 руб. Вводятся
# разрешённая и фактическая скорость — целые числа. Выведите «Штраф: N руб.»
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     60
#     75
#   в терминале:
#     Разрешённая скорость, км/ч: 60
#     Фактическая скорость, км/ч: 75
#     Штраф: 0 руб.
# Пример 2
#   ввод:
#     60
#     100
#   в терминале:
#     Разрешённая скорость, км/ч: 60
#     Фактическая скорость, км/ч: 100
#     Штраф: 750 руб.
# Пример 3
#   ввод:
#     90
#     150
#   в терминале:
#     Разрешённая скорость, км/ч: 90
#     Фактическая скорость, км/ч: 150
#     Штраф: 1500 руб.
# Пример 4
#   ввод:
#     110
#     175
#   в терминале:
#     Разрешённая скорость, км/ч: 110
#     Фактическая скорость, км/ч: 175
#     Штраф: 2500 руб.
# Пример 5
#   ввод:
#     40
#     121
#   в терминале:
#     Разрешённая скорость, км/ч: 40
#     Фактическая скорость, км/ч: 121
#     Штраф: 5000 руб.

# Решение
normal_speed=int(input("Разрешённая скорость, км/ч: "))
actual_speed=int(input("Фактическая скорость, км/ч: "))

over_speed= actual_speed - normal_speed

if over_speed <= 20:
    bill = 0
elif over_speed <= 40:
    bill = 750
elif over_speed <= 60:
    bill = 1500
elif over_speed <= 80:
    bill = 2500
else:
    bill = 5000

print(f"Щтраф: {bill} руб.")